const { chromium } = require("playwright");
const path = require("path");
const URL = "file://" + path.resolve(__dirname, "../dist/index.html");
const SHOTS = path.resolve(__dirname, "../shots");
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined });
  const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", e => errors.push("pageerror: " + e.message));
  page.on("console", m => { if (m.type() === "error" && !/fonts\.googleapis|ERR_|net::/.test(m.text())) errors.push("console: " + m.text()); });
  await page.goto(URL);
  await page.waitForSelector("#loginForm");
  await page.screenshot({ path: SHOTS + "/01-login.png" });
  await page.click("#loginForm button[type=submit]");
  await page.waitForSelector("#inboxTitle");
  await page.screenshot({ path: SHOTS + "/02-inbox.png", fullPage: true });
  console.log("inbox title:", await page.textContent("#inboxTitle"));
  await page.click("#row-S04");
  await page.waitForSelector("#nextCard");
  await page.screenshot({ path: SHOTS + "/03-nova.png", fullPage: true });
  await page.goto(URL + "#supplier-S01"); await page.waitForSelector("#sumCard");
  await page.click("#sumCard .cite");
  await page.click('[data-action="ask-rec"][data-i="1"]');
  await page.screenshot({ path: SHOTS + "/04-shree.png", fullPage: true });
  await page.click('[data-action="casefile"]'); await page.waitForSelector("#casePages");
  await page.screenshot({ path: SHOTS + "/05-casefile.png" });
  await page.click('[data-action="modal-close"]');
  await page.goto(URL + "#rules"); await page.waitForSelector("#rulesCard");
  await page.fill("#param-R1", "5"); await page.dispatchEvent("#param-R1", "change");
  await page.waitForSelector("#diffPanel");
  await page.screenshot({ path: SHOTS + "/06-rules.png", fullPage: true });
  console.log("diff:", (await page.textContent("#diffPanel")).replace(/\s+/g, " ").slice(0, 300));
  await page.click('[data-action="rule-cancel"]');
  await page.goto(URL + "#dashboard"); await page.waitForSelector("#aiQuality");
  await page.screenshot({ path: SHOTS + "/07-dashboard.png", fullPage: true });
  // approve Nova and move time
  await page.goto(URL + "#supplier-S04"); await page.waitForSelector("#nextCard");
  await page.click('[data-action="send-ask"]'); await page.click('[data-action="send-confirm"]');
  await page.waitForTimeout(300);
  await page.click('[data-action="time-next"]'); await page.waitForSelector(".modal");
  await page.screenshot({ path: SHOTS + "/08-jump1.png" });
  await page.click('.modal [data-action="modal-close"]');
  await page.goto(URL + "#inbox"); await page.waitForSelector("#inboxTitle");
  await page.screenshot({ path: SHOTS + "/09-inbox-t1.png", fullPage: true });
  await page.click('[data-action="time-next"]'); await page.waitForSelector(".modal");
  await page.screenshot({ path: SHOTS + "/10-jump2.png" });
  await page.click('.modal [data-action="modal-close"]');
  await page.goto(URL + "#dashboard"); await page.waitForSelector("#aiQuality");
  await page.screenshot({ path: SHOTS + "/11-dash-t2.png", fullPage: true });
  // phone
  const m = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  const p2 = await m.newPage(); p2.on("pageerror", e => errors.push("mobile pageerror: " + e.message));
  await p2.goto(URL); await p2.click("#loginForm button[type=submit]"); await p2.waitForSelector("#inboxTitle");
  const ov = async (pg, label) => { const w = await pg.evaluate(() => [document.documentElement.scrollWidth, document.documentElement.clientWidth]); if (w[0] > w[1]) errors.push(`horizontal scroll on ${label}: ${w[0]} > ${w[1]}`); };
  await ov(p2, "inbox"); await p2.screenshot({ path: SHOTS + "/12-phone-inbox.png", fullPage: true });
  for (const h of ["supplier-S04", "supplier-S01", "rules", "dashboard", "about"]) { await p2.goto(URL + "#" + h); await p2.waitForTimeout(250); await ov(p2, h); }
  await p2.goto(URL + "#supplier-S01"); await p2.waitForTimeout(200); await p2.screenshot({ path: SHOTS + "/13-phone-supplier.png", fullPage: true });
  console.log(errors.length ? "ERRORS:\n" + errors.join("\n") : "no errors");
  await browser.close();
})().catch(e => { console.error("FAILED", e); process.exit(1); });
